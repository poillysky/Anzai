def _assert_batch() -> None:
    ids = [c["id"] for c in CARDS]
    if len(CARDS) != 50:
        raise SystemExit(f"need 50 cards, got {len(CARDS)}")
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate ids in batch")
    existing = {r["id"] for r in pg.list_cards()}
    overlap = existing & set(ids)
    if overlap:
        raise SystemExit(f"overlap with DB: {sorted(overlap)}")


def _write_markdown() -> None:
    out = Path(__file__).resolve().parents[1] / "data" / "knowledge"
    out.mkdir(parents=True, exist_ok=True)
    for c in CARDS:
        text = (
            "---\n"
            f"id: {c['id']}\n"
            f"title: {c['title']}\n"
            f"tags: {c['tags']}\n"
            f"source: {SOURCE}\n"
            f"date: {DATE}\n"
            "---\n"
            f"{c['body']}\n"
        )
        (out / f"{c['id']}.md").write_text(text, encoding="utf-8")


def main() -> None:
    reload_settings()
    _assert_batch()
    k.reset_embed_cooldown()
    _write_markdown()
    emb = 0
    for i, c in enumerate(CARDS, 1):
        result = k.save_card(
            card_id=c["id"],
            title=c["title"],
            tags=c["tags"],
            source=SOURCE,
            card_date=DATE,
            body=c["body"],
            path="admin-seed",
            reembed=True,
        )
        embedded = bool(result.get("embedded"))
        emb += int(embedded)
        print(("OK" if embedded else "WARN"), f"{i}/50", c["id"])
    total, with_e = pg.count_cards()
    print(f"done embedded={emb}/50; db total={total} with_embedding={with_e}")


if __name__ == "__main__":
    main()
