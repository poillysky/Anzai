def _write(card: dict[str, str]) -> Path:
    path = DIR / f"{card['id']}.md"
    path.write_text(
        f"---\n"
        f"id: {card['id']}\n"
        f"title: {card['title']}\n"
        f"tags: {card['tags']}\n"
        f"source: {card['source']}\n"
        f"date: {DATE}\n"
        f"---\n"
        f"{card['body'].strip()}\n",
        encoding="utf-8",
    )
    return path


def main() -> None:
    reload_settings()
    DIR.mkdir(parents=True, exist_ok=True)
    for c in CARDS:
        print("wrote", _write(c).name)
    print("sync", k.sync_markdown_to_postgres())
    for q in ("实际利率和黄金", "杜邦分析", "Brinson归因", "修正久期", "隐含波动率", "有效前沿"):
        hits = k.search_cards(q, limit=3, mode="advanced")
        print("Q:", q)
        for card, score, ch in hits:
            lvl = "专业" if "专业" in (card.tags or []) else "基础"
            print(f"  {score:.3f} [{ch}][{lvl}] {card.id} · {card.title}")


if __name__ == "__main__":
    main()
