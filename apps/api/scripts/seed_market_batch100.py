# 本批次只要 100 条；列表里多写的先截断，避免超发。
CARDS = CARDS[:100]


def _assert_unique_and_fresh() -> None:
    ids = [c["id"] for c in CARDS]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate ids in CARDS")
    if len(CARDS) != 100:
        raise SystemExit(f"expected 100 cards, got {len(CARDS)}")
    existing = {r["id"] for r in pg.list_cards()}
    overlap = existing & set(ids)
    if overlap:
        raise SystemExit(f"overlap with DB: {sorted(overlap)[:20]}")


def _write_markdown() -> None:
    out = Path(__file__).resolve().parents[1] / "data" / "knowledge"
    out.mkdir(parents=True, exist_ok=True)
    for c in CARDS:
        text = (
            "---\n"
            f"id: {c['id']}\n"
            f"title: {c['title']}\n"
            f"tags: {c['tags']}\n"
            f"source: {SOURCE}\n"
            f"date: {DATE}\n"
            "---\n"
            f"{c['body']}\n"
        )
        (out / f"{c['id']}.md").write_text(text, encoding="utf-8")


def main() -> None:
    reload_settings()
    _assert_unique_and_fresh()
    k.reset_embed_cooldown()
    _write_markdown()
    ok = emb = 0
    for i, c in enumerate(CARDS, 1):
        result = k.save_card(
            card_id=c["id"],
            title=c["title"],
            tags=c["tags"],
            source=SOURCE,
            card_date=DATE,
            body=c["body"],
            path="admin-seed",
            reembed=True,
        )
        embedded = bool(result.get("embedded"))
        ok += 1
        emb += int(embedded)
        if i % 10 == 0 or not embedded:
            print(
                ("OK" if embedded else "WARN"),
                f"{i}/100",
                result.get("id"),
                "embedded=",
                embedded,
            )
    total, with_e = pg.count_cards()
    print(f"done ok={ok} embedded={emb}; db total={total} with_embedding={with_e}")


if __name__ == "__main__":
    main()
