def _write_md(card: dict[str, str]) -> Path:
    path = DIR / f"{card['id']}.md"
    text = (
        f"---\n"
        f"id: {card['id']}\n"
        f"title: {card['title']}\n"
        f"tags: {card['tags']}\n"
        f"source: {SOURCE}\n"
        f"date: {DATE}\n"
        f"---\n"
        f"{card['body'].strip()}\n"
    )
    path.write_text(text, encoding="utf-8")
    return path


def main() -> None:
    reload_settings()
    DIR.mkdir(parents=True, exist_ok=True)
    for c in CARDS:
        p = _write_md(c)
        print("wrote", p.name)

    result = k.sync_markdown_to_postgres()
    print("sync", result)
    for q in ("A类和C类怎么选", "定投是不是不会亏", "纯债基金会亏损吗", "15点之后买基金"):
        hits = k.search_cards(q, limit=3)
        print("Q:", q)
        for card, score, ch in hits:
            print(f"  {score:.3f} [{ch}] {card.id} · {card.title}")


if __name__ == "__main__":
    main()
