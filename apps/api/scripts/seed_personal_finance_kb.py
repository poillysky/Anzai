def _write_md(card: dict[str, str]) -> Path:
    path = DIR / f"{card['id']}.md"
    text = (
        f"---\n"
        f"id: {card['id']}\n"
        f"title: {card['title']}\n"
        f"tags: {card['tags']}\n"
        f"source: {card['source']}\n"
        f"date: {DATE}\n"
        f"---\n"
        f"{card['body'].strip()}\n"
    )
    path.write_text(text, encoding="utf-8")
    return path


